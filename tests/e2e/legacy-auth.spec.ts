import { assertTestDatabase } from '../helpers/test-database';
import { randomUUID } from 'node:crypto';
import { PrismaClient } from '@prisma/client';
import { expect, test } from '@playwright/test';

// Isolate this fixture from the other journey's localhost login-rate bucket.
test.use({ extraHTTPHeaders: { 'x-forwarded-for': '192.0.2.17' } });

test('an existing legacy credential retains its account and profile after signing in', async ({
  request,
  baseURL,
}) => {
  assertTestDatabase();
  const db = new PrismaClient();
  const runId = randomUUID();
  const userId = `legacy-user-${runId}`;
  const accountId = `legacy-account-${runId}`;
  const email = `bondi-e2e-${runId}-legacy@example.test`;
  const password = 'LegacySyntheticPassword42!';
  // Generated by Better Auth 1.3.33 before upgrading, using only this synthetic password.
  const legacyHash =
    '1d626081467bc7de53774d4ba1e2e332:67a4de6f08ef0471d48b9bc52ffe2f9eaf44b9aaea0723b15f37a2e9e2ae16a6d8231198075601dd5bbb73b3386b2cc26ea94b7b5632edfe3b751935a3b972da';
  try {
    const user = await db.user.create({
      data: {
        id: userId,
        name: 'Synthetic Legacy',
        email,
        accounts: {
          create: {
            id: accountId,
            accountId: userId,
            providerId: 'credential',
            password: legacyHash,
          },
        },
        profile: {
          create: {
            name: 'Synthetic Legacy',
            age: 28,
            bio: 'A synthetic existing profile retained across an auth upgrade.',
            gender: 'OTHER',
            interests: ['Music'],
            hobbies: ['Reading'],
          },
        },
      },
      include: { profile: true },
    });
    expect((await request.get('/api/profile')).status()).toBe(401);
    const rejected = await request.post('/api/auth/sign-in/email', {
      headers: { Origin: baseURL! },
      data: { email, password: 'IncorrectSyntheticPassword42!' },
    });
    expect(rejected.status()).toBe(401);
    const signedIn = await request.post('/api/auth/sign-in/email', {
      headers: { Origin: baseURL! },
      data: { email, password },
    });
    expect(signedIn.status()).toBe(200);
    expect((await signedIn.json()).user.id).toBe(userId);
    const profile = await request.get('/api/profile');
    expect(profile.status()).toBe(200);
    expect((await profile.json()).profile).toMatchObject({ id: user.profile!.id, userId });
    expect(await db.account.count({ where: { userId } })).toBe(1);
    expect(await db.account.findUnique({ where: { id: accountId } })).toMatchObject({
      userId,
      providerId: 'credential',
    });
    expect(
      (
        await request.post('/api/auth/sign-out', { headers: { Origin: baseURL! }, data: {} })
      ).status(),
    ).toBe(200);
    expect((await request.get('/api/profile')).status()).toBe(401);
  } finally {
    try {
      await db.user.deleteMany({ where: { id: userId, email } });
    } finally {
      await db.$disconnect();
    }
  }
});
